// Rebuild after editing an SVG: node build-electrode-assets.cjs
// SVG files remain the only hand-edited geometry source.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = __dirname;
const layouts = vm.runInNewContext(fs.readFileSync(path.join(root, 'electrodes.js'), 'utf8') + '\nELECTRODE_LAYOUTS');
const images = Object.fromEntries(layouts.map(layout => [layout.file,
  'data:image/svg+xml;base64,' + fs.readFileSync(path.join(root, layout.file)).toString('base64')]));
const output = "'use strict';\n// Generated by build-electrode-assets.cjs. Do not edit manually.\nconst ELECTRODE_IMAGES = Object.freeze(" + JSON.stringify(images, null, 2) + ");\n";
const destination = path.join(root, 'electrode-assets.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    throw new Error('Electrode bundle is outdated. Run node build-electrode-assets.cjs');
  }
  console.log('All 7 embedded electrode images match their SVG sources.');
} else {
  fs.writeFileSync(destination, output);
}
